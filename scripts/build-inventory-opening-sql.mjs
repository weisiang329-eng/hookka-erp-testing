// Build the inventory_opening load SQL (WIP/FG opening-stock seed) from the
// extracted 30/04 stock-take totals. Single source of truth = opening-stock.json
// (so the seed values can't drift from what Phase 0 extracted). Re-runnable
// (ON CONFLICT DO UPDATE). The owner runs the output in the PROD Supabase.
//
//   node scripts/build-inventory-opening-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";

const stock = JSON.parse(readFileSync("scripts/out/opening-stock.json", "utf8"));
const UPDATED_AT = "2026-06-30T00:00:00.000Z"; // fixed (no Date.now → deterministic)
const asOf = stock.asOf; // "2026-04-30"

const rows = [
  ["invopen-hookka-WIP", "WIP", stock.wipSen],
  ["invopen-hookka-FG", "FG", stock.fgSen],
];

const values = rows
  .map(([id, layer, sen]) => `  ('${id}', 'hookka', '${layer}', ${sen}, '${asOf}', '${UPDATED_AT}')`)
  .join(",\n");

const sql = `-- inventory_opening load — WIP / finished-goods opening stock (30/04 stock-take).
-- Generated by scripts/build-inventory-opening-sql.mjs from scripts/out/opening-stock.json.
-- Re-runnable (ON CONFLICT DO UPDATE). Run in the PROD Supabase (erp.hookka.com's DB).
CREATE TABLE IF NOT EXISTS inventory_opening (
  id         TEXT PRIMARY KEY,
  org_id     TEXT NOT NULL DEFAULT 'hookka',
  layer      TEXT NOT NULL,
  value_sen  INTEGER NOT NULL DEFAULT 0,
  as_of_date TEXT,
  updated_at TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_inventory_opening_key ON inventory_opening (org_id, layer);
INSERT INTO inventory_opening (id, org_id, layer, value_sen, as_of_date, updated_at) VALUES
${values}
ON CONFLICT (org_id, layer) DO UPDATE
  SET value_sen = EXCLUDED.value_sen, as_of_date = EXCLUDED.as_of_date, updated_at = EXCLUDED.updated_at;
`;

writeFileSync("scripts/out/inventory-opening-load.sql", sql);
console.log(sql);
console.log(`WIP=${stock.wipSen} (RM ${(stock.wipSen / 100).toFixed(2)})  FG=${stock.fgSen} (RM ${(stock.fgSen / 100).toFixed(2)})  asOf=${asOf}`);
